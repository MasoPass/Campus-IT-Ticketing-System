-- Service Level Agreement targets per priority, in minutes.
--   response   = time until IT first responds
--   resolution = time until the issue is resolved
CREATE TABLE IF NOT EXISTS sla_policies (
    priority            TEXT    PRIMARY KEY CHECK (priority IN ('URGENT', 'HIGH', 'MEDIUM', 'LOW')),
    response_minutes    INTEGER NOT NULL CHECK (response_minutes > 0),
    resolution_minutes  INTEGER NOT NULL CHECK (resolution_minutes >= response_minutes)
);

INSERT OR IGNORE INTO sla_policies (priority, response_minutes, resolution_minutes) VALUES
    ('URGENT',   60,   240),     -- 1 h  / 4 h
    ('HIGH',    240,  1440),     -- 4 h  / 1 day
    ('MEDIUM', 1440,  4320),     -- 1 day / 3 days
    ('LOW',    2880, 10080);     -- 2 days / 7 days

CREATE TABLE IF NOT EXISTS tickets (
    id                  INTEGER PRIMARY KEY AUTOINCREMENT,
    title               TEXT    NOT NULL,
    description         TEXT    NOT NULL,
    category_id         INTEGER NOT NULL REFERENCES categories(id),
    priority            TEXT    NOT NULL DEFAULT 'MEDIUM'
                        CHECK (priority IN ('URGENT', 'HIGH', 'MEDIUM', 'LOW')),
    status              TEXT    NOT NULL DEFAULT 'NEW'
                        CHECK (status IN ('NEW', 'ASSIGNED', 'IN_PROGRESS', 'WAITING_ON_USER', 'RESOLVED', 'CLOSED')),
    requester_id        INTEGER NOT NULL REFERENCES users(id),
    assignee_id         INTEGER REFERENCES users(id),
    device_type         TEXT    NOT NULL
                        CHECK (device_type IN ('LAPTOP', 'DESKTOP', 'PHONE', 'TABLET', 'PRINTER', 'CLASSROOM_AV', 'NETWORK', 'OTHER')),
    device_details      TEXT,
    building            TEXT    NOT NULL,
    room                TEXT,
    resolution          TEXT,
    created_at          TEXT    NOT NULL,
    updated_at          TEXT    NOT NULL,
    first_response_at   TEXT,
    resolved_at         TEXT,
    closed_at           TEXT,
    response_due_at     TEXT    NOT NULL,
    resolution_due_at   TEXT    NOT NULL,
    -- A resolved or closed ticket must say how it was resolved.
    CHECK (status NOT IN ('RESOLVED', 'CLOSED') OR resolution IS NOT NULL),
    -- An ASSIGNED ticket must have someone assigned.
    CHECK (status <> 'ASSIGNED' OR assignee_id IS NOT NULL)
);

-- Queue views: "open tickets by status/priority", "my tickets", "a student's tickets".
CREATE INDEX IF NOT EXISTS idx_tickets_status_priority ON tickets(status, priority);
CREATE INDEX IF NOT EXISTS idx_tickets_assignee_status ON tickets(assignee_id, status);
CREATE INDEX IF NOT EXISTS idx_tickets_requester ON tickets(requester_id, created_at);
-- Partial index: only OPEN tickets, sorted by deadline. The overdue check scans just this
-- small index instead of every ticket ever filed (most of which are closed).
CREATE INDEX IF NOT EXISTS idx_tickets_open_due ON tickets(resolution_due_at)
    WHERE status NOT IN ('RESOLVED', 'CLOSED');

-- Conversation + timeline. MESSAGE = written by a person, EVENT = generated by the system
-- ("Alex changed status to In progress"). INTERNAL entries are never shown to students.
CREATE TABLE IF NOT EXISTS ticket_comments (
    id          INTEGER PRIMARY KEY AUTOINCREMENT,
    ticket_id   INTEGER NOT NULL REFERENCES tickets(id) ON DELETE CASCADE,
    author_id   INTEGER NOT NULL REFERENCES users(id),
    kind        TEXT    NOT NULL CHECK (kind IN ('MESSAGE', 'EVENT')),
    visibility  TEXT    NOT NULL CHECK (visibility IN ('PUBLIC', 'INTERNAL')),
    body        TEXT    NOT NULL,
    created_at  TEXT    NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_comments_ticket ON ticket_comments(ticket_id, id);

-- Full-text search over title + description + messages (rowid = ticket id).
CREATE VIRTUAL TABLE IF NOT EXISTS tickets_fts USING fts5(body, tokenize = 'porter unicode61');
