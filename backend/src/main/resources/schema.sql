-- CampusDesk schema (SQLite). Runs on every startup, so everything is IF NOT EXISTS / OR IGNORE.
-- All timestamps are UTC strings in ONE fixed format, e.g. 2026-11-12T19:04:05.123Z, written
-- by Java (see Times.java). A fixed format means plain string comparison (<, >, ORDER BY)
-- sorts them correctly in time order.

CREATE TABLE IF NOT EXISTS users (
    id              INTEGER PRIMARY KEY AUTOINCREMENT,
    email           TEXT    NOT NULL UNIQUE COLLATE NOCASE,
    full_name       TEXT    NOT NULL,
    role            TEXT    NOT NULL CHECK (role IN ('STUDENT', 'TECHNICIAN', 'ADMIN')),
    student_number  TEXT    UNIQUE,
    password_hash   TEXT    NOT NULL,          -- "pbkdf2-sha256$iterations$salt$hash" (never the password)
    active          INTEGER NOT NULL DEFAULT 1 CHECK (active IN (0, 1)),
    created_at      TEXT    NOT NULL,
    last_login_at   TEXT,
    -- Students must have a student number. Staff may not.
    CHECK (role <> 'STUDENT' OR student_number IS NOT NULL)
);

-- Lookup table instead of a hard-coded list, so admins can add categories and tickets
-- reference them by id (a foreign key) rather than by repeating the name.
CREATE TABLE IF NOT EXISTS categories (
    id          INTEGER PRIMARY KEY AUTOINCREMENT,
    name        TEXT    NOT NULL UNIQUE COLLATE NOCASE,
    sort_order  INTEGER NOT NULL DEFAULT 50,
    active      INTEGER NOT NULL DEFAULT 1 CHECK (active IN (0, 1))
);

